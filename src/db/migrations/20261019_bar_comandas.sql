-- ArenaPro: Bar / Comandas (sem controle de estoque)
-- Execute este arquivo no SQL Editor do Supabase antes de usar o módulo.

CREATE TABLE IF NOT EXISTS public.bar_products (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  arena_id uuid NOT NULL REFERENCES public.arenas(id) ON DELETE CASCADE,
  name varchar(160) NOT NULL,
  category varchar(80) NOT NULL DEFAULT 'Geral',
  price numeric(12,2) NOT NULL CHECK (price >= 0),
  active boolean NOT NULL DEFAULT true,
  created_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (arena_id, name)
);

CREATE TABLE IF NOT EXISTS public.bar_tabs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  arena_id uuid NOT NULL REFERENCES public.arenas(id) ON DELETE CASCADE,
  tab_number bigint GENERATED BY DEFAULT AS IDENTITY,
  customer_name varchar(160) NOT NULL,
  customer_id uuid REFERENCES public.customers(id) ON DELETE SET NULL,
  reservation_id uuid REFERENCES public.reservations(id) ON DELETE SET NULL,
  court_id uuid REFERENCES public.courts(id) ON DELETE SET NULL,
  notes text,
  status text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED','CANCELLED')),
  total_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
  paid_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
  opened_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  closed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (paid_amount <= total_amount)
);

CREATE TABLE IF NOT EXISTS public.bar_tab_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  arena_id uuid NOT NULL REFERENCES public.arenas(id) ON DELETE CASCADE,
  tab_id uuid NOT NULL REFERENCES public.bar_tabs(id) ON DELETE CASCADE,
  product_id uuid REFERENCES public.bar_products(id) ON DELETE SET NULL,
  product_name varchar(160) NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  subtotal numeric(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.bar_tab_payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  arena_id uuid NOT NULL REFERENCES public.arenas(id) ON DELETE CASCADE,
  tab_id uuid NOT NULL REFERENCES public.bar_tabs(id) ON DELETE CASCADE,
  request_key uuid NOT NULL DEFAULT gen_random_uuid(),
  amount numeric(12,2) NOT NULL CHECK (amount > 0),
  payment_method public.payment_method NOT NULL,
  notes text,
  received_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  financial_transaction_id uuid REFERENCES public.financial_transactions(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (arena_id, request_key)
);

ALTER TABLE public.bar_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bar_tabs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bar_tab_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bar_tab_payments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Bar products by arena" ON public.bar_products;
CREATE POLICY "Bar products by arena" ON public.bar_products FOR ALL
  USING (public.has_arena_access(arena_id)) WITH CHECK (public.has_arena_access(arena_id));
DROP POLICY IF EXISTS "Bar tabs by arena" ON public.bar_tabs;
CREATE POLICY "Bar tabs by arena" ON public.bar_tabs FOR ALL
  USING (public.has_arena_access(arena_id)) WITH CHECK (public.has_arena_access(arena_id));
DROP POLICY IF EXISTS "Bar tab items by arena" ON public.bar_tab_items;
CREATE POLICY "Bar tab items by arena" ON public.bar_tab_items FOR ALL
  USING (public.has_arena_access(arena_id)) WITH CHECK (public.has_arena_access(arena_id));
DROP POLICY IF EXISTS "Bar tab payments by arena" ON public.bar_tab_payments;
CREATE POLICY "Bar tab payments by arena" ON public.bar_tab_payments FOR ALL
  USING (public.has_arena_access(arena_id)) WITH CHECK (public.has_arena_access(arena_id));

CREATE INDEX IF NOT EXISTS idx_bar_products_arena ON public.bar_products(arena_id, active);
CREATE INDEX IF NOT EXISTS idx_bar_tabs_arena_status ON public.bar_tabs(arena_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_bar_items_tab ON public.bar_tab_items(tab_id);
CREATE INDEX IF NOT EXISTS idx_bar_payments_tab ON public.bar_tab_payments(tab_id);

-- Recalcula total da comanda sempre que itens forem incluídos/removidos/alterados.
CREATE OR REPLACE FUNCTION public.refresh_bar_tab_total()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE target_tab uuid;
BEGIN
  target_tab := COALESCE(NEW.tab_id, OLD.tab_id);
  UPDATE public.bar_tabs bt
  SET total_amount = COALESCE((SELECT SUM(i.subtotal) FROM public.bar_tab_items i WHERE i.tab_id = target_tab), 0),
      updated_at = now()
  WHERE bt.id = target_tab;
  RETURN COALESCE(NEW, OLD);
END; $$;
DROP TRIGGER IF EXISTS trg_refresh_bar_tab_total ON public.bar_tab_items;
CREATE TRIGGER trg_refresh_bar_tab_total AFTER INSERT OR UPDATE OR DELETE ON public.bar_tab_items
FOR EACH ROW EXECUTE FUNCTION public.refresh_bar_tab_total();

-- Pagamento atômico: registra pagamento e exatamente uma receita financeira.
-- request_key permite repetir uma requisição sem duplicar recebimento.
CREATE OR REPLACE FUNCTION public.register_bar_tab_payment(
  p_tab_id uuid,
  p_amount numeric,
  p_payment_method public.payment_method,
  p_request_key uuid,
  p_notes text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_tab public.bar_tabs%ROWTYPE;
  v_existing public.bar_tab_payments%ROWTYPE;
  v_payment_id uuid;
  v_transaction_id uuid;
  v_new_paid numeric(12,2);
BEGIN
  SELECT * INTO v_tab FROM public.bar_tabs WHERE id = p_tab_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Comanda não encontrada.'; END IF;
  IF NOT public.has_arena_access(v_tab.arena_id) THEN RAISE EXCEPTION 'Sem permissão para esta arena.'; END IF;

  SELECT * INTO v_existing FROM public.bar_tab_payments
    WHERE arena_id = v_tab.arena_id AND request_key = p_request_key;
  IF FOUND THEN
    RETURN jsonb_build_object('payment_id', v_existing.id, 'financial_transaction_id', v_existing.financial_transaction_id, 'duplicate', true);
  END IF;

  IF v_tab.status <> 'OPEN' THEN RAISE EXCEPTION 'Esta comanda não está aberta.'; END IF;
  IF p_amount <= 0 THEN RAISE EXCEPTION 'O valor do pagamento deve ser maior que zero.'; END IF;
  IF p_amount > (v_tab.total_amount - v_tab.paid_amount) THEN RAISE EXCEPTION 'O pagamento excede o saldo da comanda.'; END IF;

  INSERT INTO public.bar_tab_payments(arena_id, tab_id, request_key, amount, payment_method, notes, received_by)
  VALUES (v_tab.arena_id, v_tab.id, p_request_key, p_amount, p_payment_method, p_notes, auth.uid())
  RETURNING id INTO v_payment_id;

  INSERT INTO public.financial_transactions(arena_id, type, category, description, amount, payment_method, transaction_date, status, notes, created_by)
  VALUES (v_tab.arena_id, 'INCOME', 'Bar / Comandas', 'Recebimento da comanda #' || v_tab.tab_number || ' — ' || v_tab.customer_name,
          p_amount, p_payment_method, (now() AT TIME ZONE 'America/Sao_Paulo')::date, 'COMPLETED',
          COALESCE(p_notes, 'Pagamento da comanda ' || v_tab.id), auth.uid())
  RETURNING id INTO v_transaction_id;

  UPDATE public.bar_tab_payments SET financial_transaction_id = v_transaction_id WHERE id = v_payment_id;
  v_new_paid := v_tab.paid_amount + p_amount;
  UPDATE public.bar_tabs SET paid_amount = v_new_paid,
    status = CASE WHEN v_new_paid >= v_tab.total_amount THEN 'CLOSED' ELSE 'OPEN' END,
    closed_at = CASE WHEN v_new_paid >= v_tab.total_amount THEN now() ELSE NULL END,
    updated_at = now()
  WHERE id = v_tab.id;

  RETURN jsonb_build_object('payment_id', v_payment_id, 'financial_transaction_id', v_transaction_id, 'duplicate', false);
END; $$;

REVOKE ALL ON FUNCTION public.register_bar_tab_payment(uuid,numeric,public.payment_method,uuid,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.register_bar_tab_payment(uuid,numeric,public.payment_method,uuid,text) TO authenticated;
